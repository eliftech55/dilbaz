/**
 * Safe Web Storage & Clipboard utilities for mobile WebViews, Safari Private Mode,
 * and sandboxed iframes where sessionStorage / localStorage / clipboard can throw.
 */

export function safeSessionGet(key: string): string | null {
  if (typeof window === 'undefined') return null;
  try {
    return window.sessionStorage.getItem(key);
  } catch {
    return null;
  }
}

export function safeSessionSet(key: string, value: string): void {
  if (typeof window === 'undefined') return;
  try {
    window.sessionStorage.setItem(key, value);
  } catch {
    // ignore storage restrictions in private mode / restricted webviews
  }
}

